// 从 data/raw/products.json 生成前端数据集（packages/shared/src/data/）
// 用法：node scripts/build-dataset.mjs

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const RAW = path.join(ROOT, 'data', 'raw');
const OUT = path.join(ROOT, 'packages', 'shared', 'src', 'data');
fs.mkdirSync(path.join(OUT), { recursive: true });
fs.mkdirSync(path.join(ROOT, 'data', 'clean'), { recursive: true });

const products = JSON.parse(fs.readFileSync(path.join(RAW, 'products.json'), 'utf8'));
const slugs = fs.readFileSync(path.join(RAW, 'collections.txt'), 'utf8').split('\n').map(s => s.trim()).filter(Boolean);
const collMap = JSON.parse(fs.readFileSync(path.join(RAW, 'collection-map.json'), 'utf8'));

const NATIONS = new Set(['argentina','brazil','england','france','germany','italy','spain','portugal','netherlands','japan','mexico','wales','belgium','denmark','croatia','ireland','canada','chile','cameroon','egypt','ghana','ivory-coast','algeria','morocco','nigeria','tunisia','australia','iran','iraq','jamaica','guatemala','finland','norway','sweden','poland','switzerland','austria','greece','turkey','serbia','ukraine','usa','colombia','uruguay','paraguay','peru','ecuador','bolivia','venezuela','saudi-arabia','qatar','korea','china','india','senegal','angola','south-africa','czech','romania','hungary','slovakia','slovenia','bosnia','albania','israel','scotland','northern-ireland','russia']);
const CLUBS = new Set(['barcelona','real-madrid','atletico-madrid','bayern','dortmund','arsenal','chelsea','liverpool','manchester-united','manchester-city','tottenham','newcastle','aston-villa','everton','leicester','west-ham','wolves','brighton','crystal-palace','fulham','brentford','nottingham-forest','forest','leeds','southampton','burnley','watford','sunderland','juventus','inter-milan','ac-milan','napoli','roma','lazio','atalanta','fiorentina','paris','marseille','lyon','monaco','lille','nice','benfica','porto','sporting','ajax','psv','feyenoord','club-brugge','celtic','rangers','portland','la-galaxy','inter-miami','boca-juniors','river-plate','corinthians','flamengo','fluminense','palmeiras','sao-paulo','santos','gremio','cruzeiro','chivas','club-america','pumas','monterrey','athletic-bilbao','real-sociedad','sevilla','villarreal','valencia','real-betis','sevilla','portland-timbers','seattle-sounders','la-fc','nycfc','orlando-city','atlanta-united','toronto-fc','vancouver-whitecaps']);

const label = s => s.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join(' ');

function groupOf(slug) {
  if (/^\d{4}-\d{2}-season$/.test(slug)) return 'season';
  if (slug === 'retro') return 'retro';
  if (slug === 'kids-size') return 'kids';
  if (slug === 'autumn-and-winter-series') return 'outerwear';
  if (slug.startsWith('shorts')) return 'shorts';
  if (NATIONS.has(slug)) return 'nation';
  if (CLUBS.has(slug)) return 'club';
  return 'other';
}

// ---- 商品（压缩字段）----
const slim = products.map(p => ({
  h: p.handle,
  t: p.title,
  p: p.price,
  c: p.comparePrice,
  o: p.offRatio,
  s: p.sizes || [],
  i: p.images,
  v: p.cover,
  sa: p.sales,
  cl: p.collections,
  d: p.description.slice(0, 400),
}));

// ---- 分类 ----
const categories = slugs.map(slug => ({
  slug,
  label: label(slug),
  group: groupOf(slug),
  count: collMap[slug] || 0,
})).sort((a, b) => b.count - a.count);

const groups = {};
categories.forEach(c => { (groups[c.group] ||= []).push(c); });

const ts = `// AUTO-GENERATED by scripts/build-dataset.mjs — 请勿手改
// 数据来源：data/raw/products.json（采集于 2026-10-19，共 ${products.length} 件商品）

export type SlimProduct = {
  h: string;   // handle（路由 slug）
  t: string;   // 标题
  p: number;   // 价格（USD 基准）
  c: number;   // 划线价
  o: number;   // 折扣百分比
  s: string[]; // 尺码
  i: string[]; // 图片（外链）
  v: string;   // 主图
  sa: number;  // 销量
  cl: string[];// 所属分类
  d: string;   // 描述
};

export const PRODUCTS: SlimProduct[] = ${JSON.stringify(slim)};

export type Category = { slug: string; label: string; group: string; count: number };
export const CATEGORIES: Category[] = ${JSON.stringify(categories)};

export const CATEGORY_GROUPS: Record<string, Category[]> = ${JSON.stringify(groups)};

export const GROUP_LABELS: Record<string, string> = {
  nation: 'National teams',
  club: 'Clubs',
  season: 'By season',
  retro: 'Retro',
  kids: 'Kids',
  outerwear: 'Outerwear',
  shorts: 'Shorts',
  other: 'More',
};
`;

fs.writeFileSync(path.join(OUT, 'products.ts'), ts, 'utf8');
fs.writeFileSync(path.join(OUT, 'index.ts'), "export * from './products';\n", 'utf8');

fs.writeFileSync(path.join(ROOT, 'data', 'clean', 'products.json'),
  JSON.stringify(slim), 'utf8');

console.log(`[数据集] 商品 ${slim.length} 件 · 分类 ${categories.length} 个`);
console.log(`[分组] ` + Object.entries(groups).map(([k, v]) => `${k}:${v.length}`).join('  '));
console.log(`[产出] packages/shared/src/data/products.ts`);
